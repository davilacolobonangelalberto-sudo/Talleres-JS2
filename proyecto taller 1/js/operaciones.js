// Calcular el área y perímetro de un rectángulo const base = 8;
const altura = 5;
const area = base * altura;
const perimetro = 2 * (base + altura); console.log(`Área: ${area} cm²`); console.log(`Perímetro: ${perimetro} cm`);
// Saber si un número es par o impar usando el operador % const numero = 7;
const esPar = numero % 2 === 0; console.log(`¿${numero} es par?: ${esPar}`);
// Calcular el promedio de tres notas const nota1 = 80;
const nota2 = 90; const nota3 = 70;
const promedio = (nota1 + nota2 + nota3) / 3; console.log(`Promedio: ${promedio}`);